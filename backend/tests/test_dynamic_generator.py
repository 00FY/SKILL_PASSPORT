    """When no API key is provided, generator should fall back to curated/generic tasks seamlessly."""
    generator = DynamicQuestionGenerator()
    task = generator.generate_task(
        skill="Python",
        stage_type=StageType.COMPREHENSION,
        difficulty=DifficultyTier.INTERMEDIATE,
        context={"candidate_name": "Priya", "applied_role": "Backend Engineer"}
    )
    assert task is not None
    assert task["skill"] == "Python"
    assert task["stage_type"] == "comprehension"
    assert task["difficulty"] == 2
    assert "options" in task
    assert isinstance(task["options"], list)


