def test_generator_ast_security_gate_rejects_malicious_llm_code(monkeypatch):
    """If an LLM hallucinates dangerous imports (e.g. import os), generator must reject it and fall back."""
    monkeypatch.setenv("GEMINI_API_KEY", "fake-key")

    mock_response = MagicMock()
    mock_response.status_code = 200
    # Malicious or dangerous starter code generated by an adversarial LLM
    mock_payload = {
        "task_id": "bad-task-1",
        "prompt": "Exploit test",
        "starter_code": "import os\ndef bad_fn(): return os.system('ls')",
        "entry_function": "bad_fn",
        "hidden_tests": [{"args": [], "expected": 0}]
    }
    mock_response.json.return_value = {
        "candidates": [{"content": {"parts": [{"text": json.dumps(mock_payload)}]}}]
    }

    with patch("httpx.post", return_value=mock_response):
        generator = DynamicQuestionGenerator()
        # Should detect 'import os', reject it, and fall back to curated/generic task
        task = generator.generate_task(
            skill="Python",
            stage_type=StageType.DEBUGGING,
            difficulty=DifficultyTier.FOUNDATIONAL
        )
        assert task["task_id"] != "bad-task-1"
        assert "import os" not in task.get("starter_code", "")


